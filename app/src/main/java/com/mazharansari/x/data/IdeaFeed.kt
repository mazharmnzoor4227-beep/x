package com.mazharansari.x.data

import java.text.SimpleDateFormat
import java.time.Instant
import java.time.LocalDateTime
import java.time.ZoneId
import java.util.Date
import java.util.Locale

/**
 * Idea store feed (2026-11-20): the daily-updating catalog of ideas in the
 * Ideas tab. Store ideas are kept strictly apart from the user's own saved
 * ideas — same file, different [Idea.source] ("store" vs "user") — so the
 * agent's save_idea tool can never write into the store section and the
 * daily refresh can never overwrite the user's own ideas.
 *
 * Everything here is pure (no Android calls except the date formatting
 * helpers, which are also JVM-safe), so the rules are unit-tested in
 * IdeaFeedLogicTest without Robolectric. The feed starts EMPTY: there are
 * no seed, demo or placeholder ideas anywhere — the first batch only
 * arrives from a real daily generation run (see work/IdeaFeedWorker).
 */
object IdeaFeed {
    /** The user's own ideas (typed in, or saved by the agent from chat). */
    const val SOURCE_USER = "user"

    /** Feed ideas: generated by the daily refresh, never by the user. */
    const val SOURCE_STORE = "store"

    /** Bounded history: at most this many store ideas are kept. */
    const val MAX_STORE_IDEAS = 100

    /** ...and no store idea older than this many days is kept. */
    const val MAX_STORE_AGE_DAYS = 30L

    /** One daily batch is at most this many new ideas (quota-light). */
    const val BATCH_SIZE = 5

    /** Quality bar: an idea shorter than this is too vague to start work on. */
    const val MIN_IDEA_CHARS = 20

    /** Ideas are capped at this length when stored. */
    const val MAX_IDEA_CHARS = 500

    /** Quality bar: an idea needs at least this many words to be concrete. */
    const val MIN_IDEA_WORDS = 4

    /** The only areas a generated idea may carry (the prompt enforces this). */
    val AREAS = listOf("App", "Shop", "Product", "Video", "Business")

    /** One parsed idea line from the agent's answer. */
    data class ParsedIdea(val area: String, val text: String)

    /**
     * Normalised text for dedup: case, extra whitespace and trailing
     * punctuation are ignored, so "Build a masala app." and
     * "build  a masala app" count as the same idea.
     */
    fun normalize(text: String): String =
        text.trim().lowercase().replace(Regex("\\s+"), " ").trimEnd('.', '!', '?', '"', '\'')

    /**
     * Minimal quality bar for a feed idea: concrete and actionable means
     * at least [MIN_IDEA_WORDS] words and [MIN_IDEA_CHARS] characters, with
     * real letters in it. One-word and vague lines are rejected, never
     * stored, never shown.
     */
    fun isQualityIdea(text: String): Boolean {
        val t = text.trim()
        if (t.length < MIN_IDEA_CHARS || t.length > MAX_IDEA_CHARS) return false
        if (t.split(Regex("\\s+")).size < MIN_IDEA_WORDS) return false
        if (!t.any { it.isLetter() }) return false
        return true
    }

    /**
     * Parses the agent's answer into ideas. Expected format, one per line:
     * "Area: idea in one or two sentences". Bullet / numbered prefixes and
     * wrapping quotes are stripped. A line whose prefix is not one of
     * [AREAS] keeps its whole text with area "Ideas" instead of being
     * dropped — the quality filter below still applies.
     */
    fun parseBatch(raw: String): List<ParsedIdea> {
        return raw.lines()
            .map { it.trim() }
            .filter { it.isNotEmpty() }
            .map { line ->
                var l = line.replace(Regex("^\\d+[.)]\\s+"), "").replace(Regex("^[-*•]\\s+"), "").trim()
                if (l.length >= 2 && l.startsWith("\"") && l.endsWith("\"")) l = l.substring(1, l.length - 1).trim()
                l
            }
            .filter { it.isNotEmpty() }
            .map { line ->
                val idx = line.indexOf(": ")
                if (idx in 3..24) {
                    val head = line.substring(0, idx).trim()
                    val match = AREAS.firstOrNull { it.equals(head, ignoreCase = true) }
                    if (match != null) ParsedIdea(match, line.substring(idx + 2).trim()) else ParsedIdea("Ideas", line)
                } else {
                    ParsedIdea("Ideas", line)
                }
            }
            .filter { isQualityIdea(it.text) }
    }

    /**
     * Picks the new ideas out of a generated batch: drops anything that
     * fails the quality bar, anything already in the store (user ideas and
     * store ideas alike, compared by [normalize]), and repeats inside the
     * batch itself. At most [BATCH_SIZE] survive, in the order generated.
     */
    fun selectNewIdeas(raw: String, existingTexts: Collection<String>): List<ParsedIdea> {
        val seen = existingTexts.map { normalize(it) }.toHashSet()
        val out = ArrayList<ParsedIdea>()
        for (idea in parseBatch(raw)) {
            val n = normalize(idea.text)
            if (n in seen) continue
            seen += n
            out += idea
            if (out.size >= BATCH_SIZE) break
        }
        return out
    }

    /**
     * Prunes a stored list: user ideas are NEVER pruned; store ideas older
     * than [MAX_STORE_AGE_DAYS] go, and only the newest [MAX_STORE_IDEAS]
     * store ideas survive. The list is newest-first, so the newest are
     * kept. Order is otherwise preserved.
     */
    fun prune(ideas: List<Idea>, nowMs: Long): List<Idea> {
        val cutoff = nowMs - MAX_STORE_AGE_DAYS * 24L * 3_600_000L
        var keptStore = 0
        return ideas.filter { idea ->
            if (idea.source != SOURCE_STORE) true
            else if (idea.createdAt < cutoff) false
            else if (keptStore >= MAX_STORE_IDEAS) false
            else {
                keptStore++
                true
            }
        }
    }

    /** Milliseconds until the next 07:00 local time — the daily refresh slot. */
    fun millisUntilNextMorning(nowMs: Long, hour: Int = 7): Long {
        val zone = ZoneId.systemDefault()
        val now = LocalDateTime.ofInstant(Instant.ofEpochMilli(nowMs), zone)
        var next = now.toLocalDate().atTime(hour, 0)
        if (!next.isAfter(now)) next = next.plusDays(1)
        return next.atZone(zone).toInstant().toEpochMilli() - nowMs
    }

    /** True when [createdAt] falls on the same local calendar day as [nowMs]. */
    fun isNewToday(createdAt: Long, nowMs: Long): Boolean {
        val zone = ZoneId.systemDefault()
        val a = LocalDateTime.ofInstant(Instant.ofEpochMilli(createdAt), zone).toLocalDate()
        val b = LocalDateTime.ofInstant(Instant.ofEpochMilli(nowMs), zone).toLocalDate()
        return a == b
    }

    /** Short day label for the screen, e.g. "20 Nov 2026". */
    fun dayLabel(ts: Long): String =
        SimpleDateFormat("d MMM yyyy", Locale.ENGLISH).format(Date(ts))

    /**
     * The first message X Bot receives when the user starts work on an
     * idea. The idea text goes in verbatim — X Bot can then build, plan or
     * write whatever the user asks next.
     */
    fun startWorkMessage(ideaText: String): String = "Let's build this idea: ${ideaText.trim()}"

    /**
     * The daily generation prompt. It names this user (Mazhar: 18, Karachi,
     * masala shop, Android apps, beauty products, short videos) so the
     * ideas are practical things he can actually start — not generic
     * filler — and it lists his existing ideas so the model does not
     * repeat them. The worker still dedupes afterwards; the list is a
     * second line of defence, capped so the prompt stays small.
     */
    fun buildPrompt(existingTexts: List<String>): String {
        val already = existingTexts.take(25).joinToString("; ") { it.take(100) }.ifBlank { "none yet" }
        return "You are X, coming up with fresh business and product ideas for Mazhar — 18, in Karachi, runs a masala shop, builds Android apps, sells beauty products, and makes short videos.\n" +
            "Give exactly 5 NEW ideas he could actually start this week — practical, concrete, specific to his shops, apps, products or videos. Not generic filler like \"start a business\" or \"make an app\".\n" +
            "Rules:\n" +
            "- Output ONLY the 5 ideas, one per line, in this exact format: Area: idea in one or two sentences.\n" +
            "- Area must be one of: App, Shop, Product, Video, Business.\n" +
            "- Each idea must be concrete and actionable — it must name what to build, sell or make, and for whom.\n" +
            "- Do NOT repeat any of these ideas he already has: $already\n" +
            "- Do not add greetings, numbering, explanations or anything else — just the 5 lines."
    }
}
