/**
 * Piper natural voices (2026-11-19, corrected 2026-11-20).
 *
 * The user's standing first pick for read-aloud / voice input / voice calls
 * is Piper Urdu **Aegis female** (ur_PK, ~61 MB ONNX, MIT release, distilled
 * from OmniVoice); Fasih male Urdu is the second pick; Kokoro-82M Hindi is
 * the alternative (author grades its Hindi voices C — good, not perfect).
 *
 * VERIFIED FILENAMES (2026-11-20, Hugging Face API + HEAD requests — the
 * names the code used before were WRONG and matched no real file):
 *  - Aegis: `ur_PK-aegis_female-medium.onnx` (63,515,589 bytes) +
 *    `ur_PK-aegis_female-medium.onnx.json` (5,207 bytes), repo
 *    mahwizzzz/piper-voice-ur-aegis-female. The old
 *    `ur_PK-aegis-medium.onnx` never existed on Hugging Face.
 *  - Fasih: `ur_PK-fasih-medium-model.onnx` (+ `.onnx.json`, note the
 *    "-model" infix), repo IhorShevchuk/piper-voice-ur-fasih. Different
 *    author from Aegis, so its provenance is weaker — Aegis stays the
 *    default. Fasih file sizes were NOT verified; no size is claimed here.
 *  - The old canonical names (`ur_PK-aegis-medium.onnx`,
 *    `ur_PK-fasih-medium.onnx`) survive as [PiperPack.legacyOnnxName]:
 *    they are the names the sherpa-converted copies carry
 *    (~/workspace/piper-voices/converted/), so those copies still import.
 *  - [PiperVoiceStore.downloadPack] downloads both files straight from
 *    Hugging Face. HONEST CAVEAT: the HF file is the RAW Piper release.
 *    The sherpa engine needs the converted copy (Piper metadata:
 *    model_type=vits, comment=piper, has_espeak=1) and refuses the raw
 *    file — so a downloaded pack may still fall back to the phone voice
 *    until the converted copy is imported. The converted copies at
 *    ~/workspace/piper-voices/converted/ are the working ones; the player
 *    never pretends a refused pack is speaking.
 *
 * STATE (redesign round 2, Addendum F, 2026-11-19):
 *  - The Piper engine IS bundled now: sherpa-onnx v1.10.42 (JitPack
 *    `com.github.k2-fsa:sherpa-onnx`, Apache-2.0), registered at app start
 *    (AxionApp) as [PiperVoiceEngines.engine] — see [SherpaPiperEngine].
 *  - Packs are NOT bundled (61 MB each). They are downloaded from Hugging
 *    Face ([PiperVoiceStore.downloadPack], tap a pack in Settings → Voice
 *    & Language) or imported from the user's own files (Files picker in
 *    Settings → Voice & Language): the .onnx + the .json. The .onnx MUST be
 *    the sherpa-onnx-converted file — Piper metadata in the model
 *    (model_type=vits, comment=piper, has_espeak=1). Converted copies live
 *    at ~/workspace/piper-voices/converted/ (made with the official
 *    sherpa-onnx conversion script, onnx 1.17.0); the raw
 *    aegis.onnx/fasih.onnx have no such metadata and the engine refuses them.
 *  - tokens.txt is generated by the app from the pack's .json
 *    (`phoneme_id_map`, official sherpa-onnx format: one "{phoneme} {id}"
 *    line each) the first time the pack is spoken — never hand-written.
 *  - espeak-ng-data is shared by ALL Piper packs and downloads ONCE, from
 *    https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/espeak-ng-data.tar.bz2
 *    (verified in the sherpa-onnx Piper doc). Without it the engine cannot
 *    speak and the player falls back to the phone voice with an honest notice.
 *  - Kokoro Hindi is a DIFFERENT model family (Kokoro, not Piper VITS) and
 *    needs its own sherpa-onnx config — the VITS engine does not speak it.
 *    Its pick still falls back to the phone voice until the voice research
 *    lands. Never present Kokoro audio as Piper audio, or vice versa.
 *    Its filenames below (`kokoro-hi-IN.onnx`) are PLACEHOLDERS, not real
 *    files — Kokoro has no download URL wired (see the 2026-11-20 audit).
 *    VERIFIED 2026-11-20: the sherpa-onnx `tts-models` release DOES carry
 *    `kokoro-multi-lang-v1_0.tar.bz2` and `kokoro-int8-multi-lang-v1_0.tar.bz2`
 *    (confirmed by the release's own issue #4086 and the model registry),
 *    but no verified size / SHA-256 / Hindi voice-sid mapping could be
 *    confirmed from this sandbox (the GitHub API answered 403 here), and
 *    the size claims in circulation conflict (fp32 archive ~350 MB per the
 *    lever doc, int8 126 MB per prior research, unverified). So no URL is
 *    guessed and no download is wired — wiring it needs, in order: the
 *    verified asset size + SHA-256, the Hindi voice sids, and the Kokoro
 *    branch of the bundled sherpa-onnx v1.10.42 OfflineTts config
 *    (model + voices.bin + tokens + dataDir + lexicon) proven on-device.
 *  - Amy (added 2026-11-20): Piper English Amy, female, US — the one
 *    extra free offline voice verified this round. Repo
 *    rhasspy/piper-voices, file
 *    en/en_US/amy/medium/en_US-amy-medium.onnx, 63,221,984 bytes
 *    (+ .onnx.json, 6,289 bytes), verified via the Hugging Face API file
 *    tree 2026-11-20. Same VITS engine as Aegis/Fasih, same download +
 *    import path. HF API search this round found only two Urdu Piper
 *    repos (Aegis, Fasih) and no verified Hindi VITS pack, so Amy is the
 *    only addition beyond the two Urdu packs.
 *  - Voice research is still running: the final pack choice may swap; the
 *    swap point is [PiperPack] + the default in AppSettings.voicePref.
 */
enum class PiperPack(
    val id: String,
    val displayName: String,
    val onnxName: String,
    val jsonName: String,
    /** Locale the phone's built-in voice uses as the offline stand-in. */
    val phoneLocale: String,
    /** Filenames the raw files actually carry (the import picker matches these too). */
    val shortOnnxName: String? = null,
    val shortJsonName: String? = null,
    /** Names the sherpa-converted copies carry — import matches these too, stored under the canonical name. */
    val legacyOnnxName: String? = null,
    val legacyJsonName: String? = null,
    /** Hugging Face repo base for a direct download (null = no download wired, import only). */
    val downloadBase: String? = null,
    /** Verified .onnx size in bytes (0 = unverified — never guessed, never checked). */
    val onnxBytes: Long = 0,
) {
    AEGIS("piper-aegis", "Piper Urdu Aegis (female)", "ur_PK-aegis_female-medium.onnx", "ur_PK-aegis_female-medium.onnx.json", "ur-PK", "aegis.onnx", "aegis.onnx.json",
        legacyOnnxName = "ur_PK-aegis-medium.onnx", legacyJsonName = "ur_PK-aegis-medium.onnx.json",
        downloadBase = "https://huggingface.co/mahwizzzz/piper-voice-ur-aegis-female/resolve/main", onnxBytes = 63_515_589),
    FASIH("piper-fasih", "Piper Urdu Fasih (male)", "ur_PK-fasih-medium-model.onnx", "ur_PK-fasih-medium-model.onnx.json", "ur-PK", "fasih.onnx", "fasih.onnx.json",
        legacyOnnxName = "ur_PK-fasih-medium.onnx", legacyJsonName = "ur_PK-fasih-medium.onnx.json",
        downloadBase = "https://huggingface.co/IhorShevchuk/piper-voice-ur-fasih/resolve/main"),
    /** 2026-11-20: Piper English Amy (female, US), rhasspy/piper-voices — verified .onnx size 63,221,984 bytes. */
    AMY("piper-amy", "Piper English Amy (female)", "en_US-amy-medium.onnx", "en_US-amy-medium.onnx.json", "en-US",
        downloadBase = "https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/amy/medium", onnxBytes = 63_221_984),
    KOKORO_HINDI("kokoro-hindi", "Kokoro Hindi (alternative)", "kokoro-hi-IN.onnx", "kokoro-hi-IN.onnx.json", "hi-IN");

    /** Direct download URLs for the pack's two files (null when no download is wired for this pack). */
    fun onnxUrl(): String? = downloadBase?.let { "$it/$onnxName" }
    fun jsonUrl(): String? = downloadBase?.let { "$it/$jsonName" }

    companion object {
        fun of(id: String?): PiperPack = entries.firstOrNull { it.id == id } ?: AEGIS
        fun isPiperPick(id: String?): Boolean = id == AEGIS.id || id == FASIH.id || id == AMY.id || id == KOKORO_HINDI.id
        /** Only the VITS Piper packs can run on the sherpa-onnx VITS engine (Kokoro cannot). */
        fun isVitsPack(id: String?): Boolean = id == AEGIS.id || id == FASIH.id || id == AMY.id
    }
}

/** One Piper voice pack's on-disk state. [downloaded] needs BOTH files. */
data class PiperPackStatus(val pack: PiperPack, val downloaded: Boolean, val bytes: Long)

/**
 * The voice-pack store: <filesDir>/piper-voices/<pack.id>/<onnx + json + tokens.txt>,
 * plus the shared <filesDir>/piper-voices/espeak-ng-data/ (downloaded once).
 * Packs used to live flat in piper-voices/ (pre-engine import UI); they are moved into
 * per-pack dirs on first use, because the engine needs tokens.txt next to each .onnx
 * (its modelDir is the pack dir).
 */
class PiperVoiceStore(ctx: Context) {
    private val dir = File(ctx.filesDir, "piper-voices").apply { mkdirs() }

    init {
        PiperPack.entries.forEach { pack ->
            val flatOnnx = File(dir, pack.onnxName)
            val flatJson = File(dir, pack.jsonName)
            if (flatOnnx.isFile || flatJson.isFile) {
                val pd = packDir(pack).apply { mkdirs() }
                if (flatOnnx.isFile) flatOnnx.renameTo(File(pd, pack.onnxName))
                if (flatJson.isFile) flatJson.renameTo(File(pd, pack.jsonName))
            }
        }
    }

    fun packDir(pack: PiperPack): File = File(dir, pack.id)
    fun espeakDir(): File = File(dir, "espeak-ng-data")

    fun status(pack: PiperPack): PiperPackStatus {
        val onnx = onnxFile(pack)
        val json = jsonFile(pack)
        val ok = onnx.isFile && onnx.length() > 1_000_000 && json.isFile
        return PiperPackStatus(pack, ok, (if (onnx.isFile) onnx.length() else 0L) + (if (json.isFile) json.length() else 0L))
    }

    fun statusFor(prefId: String?): PiperPackStatus = status(PiperPack.of(prefId))

    fun onnxFile(pack: PiperPack): File = File(packDir(pack), pack.onnxName)
    fun jsonFile(pack: PiperPack): File = File(packDir(pack), pack.jsonName)
    fun tokensFile(pack: PiperPack): File = File(packDir(pack), "tokens.txt")

    /**
     * Generates tokens.txt for [pack] from its .json (`phoneme_id_map`), in the
     * exact format of the official sherpa-onnx conversion script (one
     * "{phoneme} {id}" line per entry, map order kept). No-op when the file
     * already exists. False when the .json is missing or unparsable — the
     * engine cannot speak that pack.
     */
    fun ensureTokens(pack: PiperPack): Boolean {
        val tokens = tokensFile(pack)
        if (tokens.isFile && tokens.length() > 0) return true
        val json = jsonFile(pack).takeIf { it.isFile }?.readText() ?: return false
        return runCatching {
            val map = Json.parseToJsonElement(json).jsonObject["phoneme_id_map"]?.jsonObject ?: return false
            tokens.parentFile?.mkdirs()
            tokens.writer(Charsets.UTF_8).use { w ->
                map.entries.forEach { (s, v) -> w.write("$s ${v.jsonArray[0].jsonPrimitive.int}\n") }
            }
            tokens.isFile && tokens.length() > 0
        }.getOrDefault(false)
    }

    /** espeak-ng-data is ready when the dir exists and holds its phoneme tables. */
    fun espeakReady(): Boolean {
        val d = espeakDir()
        return d.isDirectory && File(d, "phontab").isFile
    }

    fun espeakBytes(): Long = runCatching { espeakDir().walkTopDown().filter { it.isFile }.sumOf { it.length() } }.getOrDefault(0L)

    /**
     * Downloads one file with progress (0..100 of the response body when the
     * server reports a length). Writes to [tmp] (a .part file); the caller
     * renames it into place only after the download + any size check pass.
     * Returns false on any HTTP or I/O failure (the .part file is deleted).
     */
    private suspend fun downloadTo(client: OkHttpClient, url: String, tmp: File, onProgress: (Int) -> Unit): Boolean = withContext(Dispatchers.IO) {
        try {
            val req = Request.Builder().url(url).header("User-Agent", "X").build()
            client.newCall(req).execute().use { r ->
                if (!r.isSuccessful) return@withContext false
                val total = r.body?.contentLength() ?: -1L
                val stream = r.body?.byteStream() ?: return@withContext false
                stream.use { input ->
                    tmp.outputStream().use { out ->
                        val buf = ByteArray(1 shl 16)
                        var done = 0L
                        while (true) {
                            val n = input.read(buf)
                            if (n < 0) break
                            out.write(buf, 0, n)
                            done += n
                            if (total > 0) onProgress(((done * 100) / total).toInt().coerceIn(0, 100))
                        }
                    }
                }
            }
            true
        } catch (e: Exception) {
            tmp.delete()
            false
        }
    }

    /**
     * Downloads a VITS pack's two files (.onnx + .onnx.json) straight from
     * its verified Hugging Face repo ([PiperPack.downloadBase]) into the
     * pack dir. No-op true when the pack is already downloaded; false when
     * the pack has no download wired (Kokoro) or either file fails. The
     * .onnx size is checked when the pack carries a verified size
     * ([PiperPack.onnxBytes]); a mismatch deletes the file and fails.
     * See the [PiperPack] KDoc for the honest caveat: the HF file is the
     * raw Piper release and the sherpa engine needs the converted copy.
     */
    suspend fun downloadPack(client: OkHttpClient, pack: PiperPack, onProgress: (Int) -> Unit = {}): Boolean = withContext(Dispatchers.IO) {
        val onnxUrl = pack.onnxUrl() ?: return@withContext false
        val jsonUrl = pack.jsonUrl() ?: return@withContext false
        if (status(pack).downloaded) return@withContext true
        val pd = packDir(pack).apply { mkdirs() }
        val onnxTmp = File(pd, pack.onnxName + ".part")
        val jsonTmp = File(pd, pack.jsonName + ".part")
        try {
            if (!downloadTo(client, onnxUrl, onnxTmp) { onProgress((it * 95) / 100) }) return@withContext false
            if (pack.onnxBytes > 0 && onnxTmp.length() != pack.onnxBytes) { onnxTmp.delete(); return@withContext false }
            if (!downloadTo(client, jsonUrl, jsonTmp) { onProgress(95 + it / 20) }) { onnxTmp.delete(); return@withContext false }
            if (!onnxTmp.renameTo(File(pd, pack.onnxName))) return@withContext false
            if (!jsonTmp.renameTo(File(pd, pack.jsonName))) { File(pd, pack.onnxName).delete(); return@withContext false }
            status(pack).downloaded
        } catch (e: Exception) {
            onnxTmp.delete(); jsonTmp.delete()
            false
        }
    }

    /**
     * Downloads espeak-ng-data once (shared by all Piper packs) from the
     * verified sherpa-onnx tts-models release asset and extracts it into
     * <filesDir>/piper-voices/. The tarball is .tar.bz2; extraction applies
     * the same safety policy as LinuxRuntime.extractTarGz (no entry may
     * escape the destination; escaping symlinks are skipped, never planted).
     * Returns true when the data dir is ready afterwards. [onProgress] gets
     * 0..100 during the download (extraction has no progress — it is fast).
     */
    suspend fun downloadEspeakData(client: OkHttpClient, onProgress: (Int) -> Unit = {}): Boolean = withContext(Dispatchers.IO) {
        if (espeakReady()) return@withContext true
        val tmp = File(dir, "espeak-ng-data.tar.bz2.part")
        try {
            if (!downloadTo(client, ESPEAK_URL, tmp, onProgress)) return@withContext false
            extractTarBz2(tmp, dir)
            tmp.delete()
            espeakReady()
        } catch (e: Exception) {
            tmp.delete()
            false
        }
    }

    private fun extractTarBz2(archive: File, dest: File) {
        val canonical = dest.canonicalPath
        fun inside(path: String) = path == canonical || path.startsWith(canonical + File.separator)
        BZip2CompressorInputStream(BufferedInputStream(archive.inputStream(), 1 shl 16)).use { bz ->
            TarArchiveInputStream(bz).use { tar ->
                var e = tar.nextEntry
                while (e != null) {
                    val name = e.name.removePrefix("./").trimEnd('/')
                    if (name.isNotEmpty() && !name.startsWith("dev/")) {
                        val target = File(dest, name)
                        require(inside(target.canonicalPath)) { "Unsafe path in archive: $name" }
                        when {
                            e.isDirectory -> target.mkdirs()
                            e.isSymbolicLink -> {
                                // Same policy as LinuxRuntime.extractTarGz: absolute targets are
                                // rewritten to dest-relative; escaping targets are skipped.
                                val raw = e.linkName
                                val canonDest = Paths.get(canonical)
                                val linkParent = canonDest.resolve(name).parent
                                val stored: String? = if (File(raw).isAbsolute) {
                                    val abs = canonDest.resolve(raw.trimStart('/')).normalize()
                                    if (!inside(abs.toString())) null else linkParent.relativize(abs).toString().ifEmpty { "." }
                                } else {
                                    val resolved = linkParent.resolve(raw).normalize()
                                    if (!inside(resolved.toString())) null else raw
                                }
                                if (stored != null) {
                                    target.parentFile?.mkdirs()
                                    target.delete()
                                    runCatching { Files.createSymbolicLink(target.toPath(), Paths.get(stored)) }
                                }
                            }
                            e.isFile -> {
                                target.parentFile?.mkdirs()
                                FileOutputStream(target).use { tar.copyTo(it, 1 shl 16) }
                            }
                        }
                    }
                    e = tar.nextEntry
                }
            }
        }
    }

    /**
     * Imports one file of a pack from a user-picked document (the .onnx and
     * .json are picked one at a time from Files / Downloads / a USB copy of
     * ~/workspace/piper-voices/converted/). Matches the canonical names, the
     * short names the raw files carry (aegis.onnx, fasih.onnx) and the legacy
     * names the sherpa-converted copies carry (ur_PK-aegis-medium.onnx,
     * ur_PK-fasih-medium.onnx); the file is always stored under its canonical
     * name in the pack's dir. Returns the pack file it wrote, or null when
     * the name does not match any pack.
     */
    fun importFile(ctx: Context, uri: Uri, displayName: String): File? {
        val (pack, canonical) = PiperPack.entries.firstNotNullOfOrNull { p ->
            when (displayName) {
                p.onnxName, p.shortOnnxName, p.legacyOnnxName -> p to p.onnxName
                p.jsonName, p.shortJsonName, p.legacyJsonName -> p to p.jsonName
                else -> null
            }
        } ?: return null
        val dest = File(packDir(pack).apply { mkdirs() }, canonical)
        ctx.contentResolver.openInputStream(uri)?.use { input -> dest.outputStream().use { out -> input.copyTo(out) } } ?: return null
        return dest.takeIf { it.isFile && it.length() > 0 }
    }

    fun remove(pack: PiperPack) {
        packDir(pack).deleteRecursively()
    }

    companion object {
        /** Verified in the sherpa-onnx Piper doc; shared by all Piper packs, any language. */
        const val ESPEAK_URL = "https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/espeak-ng-data.tar.bz2"
    }
}

/**
 * The on-device Piper inference engine. Implemented by [SherpaPiperEngine]
 * (sherpa-onnx, bundled since redesign round 2). Returning false means "did
 * not speak" — the caller falls back to the phone voice with an honest notice.
 */
interface PiperVoiceEngine {
    suspend fun speak(ctx: Context, pack: PiperPack, text: String): Boolean

    /** Ask an in-flight speak to stop (read-aloud Stop / new message). Default: ignore. */
    fun stop() {}
}

object PiperVoiceEngines {
    /** Set by the app at startup (AxionApp); null in unit tests. Never faked. */
    var engine: PiperVoiceEngine? = null
}
