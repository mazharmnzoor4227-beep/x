/**
 * Piper natural voices (2026-11-19).
 *
 * The user's standing first pick for read-aloud / voice input / voice calls
 * is Piper Urdu **Aegis female** (ur_PK, ~61 MB ONNX, MIT release, distilled
 * from OmniVoice); Fasih male Urdu is the second pick; Kokoro-82M Hindi is
 * the alternative (author grades its Hindi voices C — good, not perfect).
 *
 * STATE (redesign round 2, Addendum F, 2026-11-19):
 *  - The Piper engine IS bundled now: sherpa-onnx v1.10.42 (JitPack
 *    `com.github.k2-fsa:sherpa-onnx`, Apache-2.0), registered at app start
 *    (AxionApp) as [PiperVoiceEngines.engine] — see [SherpaPiperEngine].
 *  - Packs are NOT bundled (61 MB each). They are imported from the user's
 *    own files (Files picker in Settings → Voice & Language): the .onnx +
 *    the .json. The .onnx MUST be the sherpa-onnx-converted file — Piper
 *    metadata in the model (model_type=vits, comment=piper, has_espeak=1).
 *    Converted copies live at ~/workspace/piper-voices/converted/ (made with
 *    the official sherpa-onnx conversion script, onnx 1.17.0); the raw
 *    aegis.onnx/fasih.onnx have no such metadata and the engine refuses them.
 *  - tokens.txt is generated by the app from the pack's .json
 *    (`phoneme_id_map`, official sherpa-onnx format: one "{phoneme} {id}"
 *    line each) the first time the pack is spoken — never hand-written.
 *  - espeak-ng-data is shared by ALL Piper packs and downloads ONCE, from
 *    https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/espeak-ng-data.tar.bz2
 *    (verified in the sherpa-onnx Piper doc). Without it the engine cannot
 *    speak and the player falls back to the phone voice with an honest notice.
 *  - Kokoro Hindi is a DIFFERENT model family (Kokoro, not Piper VITS) and
 *    needs its own sherpa-onnx config — the VITS engine does not speak it.
 *    Its pick still falls back to the phone voice until the voice research
 *    lands. Never present Kokoro audio as Piper audio, or vice versa.
 *  - Voice research is still running: the final pack choice may swap; the
 *    swap point is [PiperPack] + the default in AppSettings.voicePref.
 */
enum class PiperPack(
    val id: String,
    val displayName: String,
    val onnxName: String,
    val jsonName: String,
    /** Locale the phone's built-in voice uses as the offline stand-in. */
    val phoneLocale: String,
    /** Filenames the raw files actually carry (the import picker matches these too). */
    val shortOnnxName: String? = null,
    val shortJsonName: String? = null,
) {
    AEGIS("piper-aegis", "Piper Urdu Aegis (female)", "ur_PK-aegis-medium.onnx", "ur_PK-aegis-medium.onnx.json", "ur-PK", "aegis.onnx", "aegis.onnx.json"),
    FASIH("piper-fasih", "Piper Urdu Fasih (male)", "ur_PK-fasih-medium.onnx", "ur_PK-fasih-medium.onnx.json", "ur-PK", "fasih.onnx", "fasih.onnx.json"),
    KOKORO_HINDI("kokoro-hindi", "Kokoro Hindi (alternative)", "kokoro-hi-IN.onnx", "kokoro-hi-IN.onnx.json", "hi-IN");

    companion object {
        fun of(id: String?): PiperPack = entries.firstOrNull { it.id == id } ?: AEGIS
        fun isPiperPick(id: String?): Boolean = id == AEGIS.id || id == FASIH.id || id == KOKORO_HINDI.id
        /** Only the VITS Piper packs can run on the sherpa-onnx VITS engine (Kokoro cannot). */
        fun isVitsPack(id: String?): Boolean = id == AEGIS.id || id == FASIH.id
    }
}

/** One Piper voice pack's on-disk state. [downloaded] needs BOTH files. */
data class PiperPackStatus(val pack: PiperPack, val downloaded: Boolean, val bytes: Long)

/**
 * The voice-pack store: <filesDir>/piper-voices/<pack.id>/<onnx + json + tokens.txt>,
 * plus the shared <filesDir>/piper-voices/espeak-ng-data/ (downloaded once).
 * Packs used to live flat in piper-voices/ (pre-engine import UI); they are moved into
 * per-pack dirs on first use, because the engine needs tokens.txt next to each .onnx
 * (its modelDir is the pack dir).
 */
class PiperVoiceStore(ctx: Context) {
    private val dir = File(ctx.filesDir, "piper-voices").apply { mkdirs() }

    init {
        PiperPack.entries.forEach { pack ->
            val flatOnnx = File(dir, pack.onnxName)
            val flatJson = File(dir, pack.jsonName)
            if (flatOnnx.isFile || flatJson.isFile) {
                val pd = packDir(pack).apply { mkdirs() }
                if (flatOnnx.isFile) flatOnnx.renameTo(File(pd, pack.onnxName))
                if (flatJson.isFile) flatJson.renameTo(File(pd, pack.jsonName))
            }
        }
    }

    fun packDir(pack: PiperPack): File = File(dir, pack.id)
    fun espeakDir(): File = File(dir, "espeak-ng-data")

    fun status(pack: PiperPack): PiperPackStatus {
        val onnx = onnxFile(pack)
        val json = jsonFile(pack)
        val ok = onnx.isFile && onnx.length() > 1_000_000 && json.isFile
        return PiperPackStatus(pack, ok, (if (onnx.isFile) onnx.length() else 0L) + (if (json.isFile) json.length() else 0L))
    }

    fun statusFor(prefId: String?): PiperPackStatus = status(PiperPack.of(prefId))

    fun onnxFile(pack: PiperPack): File = File(packDir(pack), pack.onnxName)
    fun jsonFile(pack: PiperPack): File = File(packDir(pack), pack.jsonName)
    fun tokensFile(pack: PiperPack): File = File(packDir(pack), "tokens.txt")

    /**
     * Generates tokens.txt for [pack] from its .json (`phoneme_id_map`), in the
     * exact format of the official sherpa-onnx conversion script (one
     * "{phoneme} {id}" line per entry, map order kept). No-op when the file
     * already exists. False when the .json is missing or unparsable — the
     * engine cannot speak that pack.
     */
    fun ensureTokens(pack: PiperPack): Boolean {
        val tokens = tokensFile(pack)
        if (tokens.isFile && tokens.length() > 0) return true
        val json = jsonFile(pack).takeIf { it.isFile }?.readText() ?: return false
        return runCatching {
            val map = Json.parseToJsonElement(json).jsonObject["phoneme_id_map"]?.jsonObject ?: return false
            tokens.parentFile?.mkdirs()
            tokens.writer(Charsets.UTF_8).use { w ->
                map.entries.forEach { (s, v) -> w.write("$s ${v.jsonArray[0].jsonPrimitive.int}\n") }
            }
            tokens.isFile && tokens.length() > 0
        }.getOrDefault(false)
    }

    /** espeak-ng-data is ready when the dir exists and holds its phoneme tables. */
    fun espeakReady(): Boolean {
        val d = espeakDir()
        return d.isDirectory && File(d, "phontab").isFile
    }

    fun espeakBytes(): Long = runCatching { espeakDir().walkTopDown().filter { it.isFile }.sumOf { it.length() } }.getOrDefault(0L)

    /**
     * Downloads espeak-ng-data once (shared by all Piper packs) from the
     * verified sherpa-onnx tts-models release asset and extracts it into
     * <filesDir>/piper-voices/. The tarball is .tar.bz2; extraction applies
     * the same safety policy as LinuxRuntime.extractTarGz (no entry may
     * escape the destination; escaping symlinks are skipped, never planted).
     * Returns true when the data dir is ready afterwards. [onProgress] gets
     * 0..100 during the download (extraction has no progress — it is fast).
     */
    suspend fun downloadEspeakData(client: OkHttpClient, onProgress: (Int) -> Unit = {}): Boolean = withContext(Dispatchers.IO) {
        if (espeakReady()) return@withContext true
        val tmp = File(dir, "espeak-ng-data.tar.bz2.part")
        try {
            val req = Request.Builder().url(ESPEAK_URL).header("User-Agent", "X").build()
            client.newCall(req).execute().use { r ->
                if (!r.isSuccessful) return@withContext false
                val total = r.body?.contentLength() ?: -1L
                val stream = r.body?.byteStream() ?: return@withContext false
                stream.use { input ->
                    tmp.outputStream().use { out ->
                        val buf = ByteArray(1 shl 16)
                        var done = 0L
                        while (true) {
                            val n = input.read(buf)
                            if (n < 0) break
                            out.write(buf, 0, n)
                            done += n
                            if (total > 0) onProgress(((done * 100) / total).toInt().coerceIn(0, 100))
                        }
                    }
                }
            }
            extractTarBz2(tmp, dir)
            tmp.delete()
            espeakReady()
        } catch (e: Exception) {
            tmp.delete()
            false
        }
    }

    private fun extractTarBz2(archive: File, dest: File) {
        val canonical = dest.canonicalPath
        fun inside(path: String) = path == canonical || path.startsWith(canonical + File.separator)
        BZip2CompressorInputStream(BufferedInputStream(archive.inputStream(), 1 shl 16)).use { bz ->
            TarArchiveInputStream(bz).use { tar ->
                var e = tar.nextEntry
                while (e != null) {
                    val name = e.name.removePrefix("./").trimEnd('/')
                    if (name.isNotEmpty() && !name.startsWith("dev/")) {
                        val target = File(dest, name)
                        require(inside(target.canonicalPath)) { "Unsafe path in archive: $name" }
                        when {
                            e.isDirectory -> target.mkdirs()
                            e.isSymbolicLink -> {
                                // Same policy as LinuxRuntime.extractTarGz: absolute targets are
                                // rewritten to dest-relative; escaping targets are skipped.
                                val raw = e.linkName
                                val canonDest = Paths.get(canonical)
                                val linkParent = canonDest.resolve(name).parent
                                val stored: String? = if (File(raw).isAbsolute) {
                                    val abs = canonDest.resolve(raw.trimStart('/')).normalize()
                                    if (!inside(abs.toString())) null else linkParent.relativize(abs).toString().ifEmpty { "." }
                                } else {
                                    val resolved = linkParent.resolve(raw).normalize()
                                    if (!inside(resolved.toString())) null else raw
                                }
                                if (stored != null) {
                                    target.parentFile?.mkdirs()
                                    target.delete()
                                    runCatching { Files.createSymbolicLink(target.toPath(), Paths.get(stored)) }
                                }
                            }
                            e.isFile -> {
                                target.parentFile?.mkdirs()
                                FileOutputStream(target).use { tar.copyTo(it, 1 shl 16) }
                            }
                        }
                    }
                    e = tar.nextEntry
                }
            }
        }
    }

    /**
     * Imports one file of a pack from a user-picked document (the .onnx and
     * .json are picked one at a time from Files / Downloads / a USB copy of
     * ~/workspace/piper-voices/converted/). Matches the canonical names and
     * the short names the raw files carry (aegis.onnx, fasih.onnx); the file
     * is always stored under its canonical name in the pack's dir. Returns
     * the pack file it wrote, or null when the name does not match any pack.
     */
    fun importFile(ctx: Context, uri: Uri, displayName: String): File? {
        val (pack, canonical) = PiperPack.entries.firstNotNullOfOrNull { p ->
            when (displayName) {
                p.onnxName, p.shortOnnxName -> p to p.onnxName
                p.jsonName, p.shortJsonName -> p to p.jsonName
                else -> null
            }
        } ?: return null
        val dest = File(packDir(pack).apply { mkdirs() }, canonical)
        ctx.contentResolver.openInputStream(uri)?.use { input -> dest.outputStream().use { out -> input.copyTo(out) } } ?: return null
        return dest.takeIf { it.isFile && it.length() > 0 }
    }

    fun remove(pack: PiperPack) {
        packDir(pack).deleteRecursively()
    }

    companion object {
        /** Verified in the sherpa-onnx Piper doc; shared by all Piper packs, any language. */
        const val ESPEAK_URL = "https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/espeak-ng-data.tar.bz2"
    }
}

/**
 * The on-device Piper inference engine. Implemented by [SherpaPiperEngine]
 * (sherpa-onnx, bundled since redesign round 2). Returning false means "did
 * not speak" — the caller falls back to the phone voice with an honest notice.
 */
interface PiperVoiceEngine {
    suspend fun speak(ctx: Context, pack: PiperPack, text: String): Boolean

    /** Ask an in-flight speak to stop (read-aloud Stop / new message). Default: ignore. */
    fun stop() {}
}

object PiperVoiceEngines {
    /** Set by the app at startup (AxionApp); null in unit tests. Never faked. */
    var engine: PiperVoiceEngine? = null
}
